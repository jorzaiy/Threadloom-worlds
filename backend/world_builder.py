def _read_json(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
    except Exception:
        return {}
    return data if isinstance(data, dict) else {}


def _compact(value: Any, limit: int) -> str:
    text = re.sub(r'\s+', ' ', str(value or '')).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit]
    boundary = max(cut.rfind(mark) for mark in ('。', '！', '？', '. ', '; ', '；'))
    if boundary >= limit // 2:
        return cut[:boundary + 1].strip()
    return cut.rstrip() + '…'


def _stable_id(prefix: str, text: str) -> str:
    return f"{prefix}-{hashlib.md5(text.encode('utf-8')).hexdigest()[:10]}"


def _bigrams(text: str) -> set[str]:
    clean = re.sub(r'[\s\W_]+', '', str(text or '').lower())
    if len(clean) < 2:
        return {clean} if clean else set()
    return {clean[i:i + 2] for i in range(len(clean) - 1)}


def _similarity(a: str, b: str) -> float:
    sa, sb = _bigrams(a), _bigrams(b)
    if not sa or not sb:
        return 0.0
    # Containment-style overlap: a short inferred restatement of a long card
    # entry should still count as a duplicate.
    return len(sa & sb) / min(len(sa), len(sb))


def _has_negation(text: str) -> bool:
    lower = f' {str(text or "").lower()} '
    return any(marker in lower for marker in NEGATION_MARKERS_ZH) or any(marker in lower for marker in NEGATION_MARKERS_EN)


def empty_sections() -> dict[str, list[dict]]:
    return {name: [] for name in SECTIONS}


# ---------------------------------------------------------------------------
# card-derived entries (deterministic, no model)
# ---------------------------------------------------------------------------

def _enabled_lorebook_entries(lorebook: dict) -> list[dict]:
    entries = lorebook.get('entries', []) if isinstance(lorebook.get('entries'), list) else []
    out = []
    for index, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            continue
        if entry.get('disable') is True or entry.get('enabled') is False:
            continue
        content = str(entry.get('content', '') or '').strip()
        if not content:
            continue
        item = dict(entry)
        item['id'] = str(entry.get('id', '') or '').strip() or f'entry-{index}'
        out.append(item)
    return out


def _is_meta_entry(entry: dict) -> bool:
    haystack = f" {entry.get('title', '')} {str(entry.get('content', ''))[:300]} ".lower()
    return any(marker in haystack for marker in META_MARKERS)


def classify_section(title: str, content: str, entry_type: str = '') -> str | None:
    """Pick the best world-bible section for a lorebook entry, or ``None``."""
    title_l = str(title or '').lower()
    head_l = str(content or '')[:400].lower()
    scores: dict[str, int] = {name: 0 for name in SECTIONS}
    for section, words in SECTION_KEYWORDS.items():
        for word in words:
            if word in title_l:
                scores[section] += 3
            if word in head_l:
                scores[section] += 1
    mapped = ENTRY_TYPE_SECTION.get(str(entry_type or '').strip())
    if mapped:
        scores[mapped] += 2
    best = max(SECTIONS, key=lambda name: (scores[name], -SECTIONS.index(name)))
    return best if scores[best] > 0 else None


def _constraint_sentences(text: str, limit: int = 3) -> list[str]:
    parts = re.split(r'(?<=[。！？!?；;\n])|(?<=\.)\s+', str(text or ''))
    out = []
    for part in parts:
        sentence = part.strip()
        if 4 <= len(sentence) <= 200 and _has_negation(sentence):
            out.append(sentence)
        if len(out) >= limit:
            break
    return out


def extract_card_sections(core: dict, lorebook: dict) -> dict[str, list[dict]]:
    """Build card-sourced entries from character core + normalized lorebook."""
    sections = empty_sections()

    def add(section: str, title: str, text: str, entry_ids: list[str]) -> None:
        bucket = sections[section]
        if len(bucket) >= MAX_CARD_ENTRIES_PER_SECTION:
            return
        clean = _compact(text, CARD_ENTRY_TEXT_LIMIT)
        if not clean or any(_similarity(clean, item['text']) >= 0.9 for item in bucket):
            return
        bucket.append({
            'id': _stable_id('card', f'{section}:{clean}'),
            'title': _compact(title, 60),
            'text': clean,
            'source': SOURCE_CARD,
            'source_entry_ids': entry_ids,
        })

    core_desc = core.get('coreDescription', {}) if isinstance(core.get('coreDescription'), dict) else {}
    scenario = str(core_desc.get('tagline', '') or '').strip()
    if scenario:
        add('era_feel', 'Scenario', scenario, ['card:scenario'])

    for entry in _enabled_lorebook_entries(lorebook):
        entry_type = str(entry.get('entryType', '') or '').strip()
        if entry_type == 'npc' or _is_meta_entry(entry):
            continue
        title = str(entry.get('title', '') or entry.get('name', '') or '').strip()
        content = str(entry.get('content', '') or '')
        section = classify_section(title, content, entry_type)
        if section is None:
            continue
        add(section, title or section, content, [entry['id']])
        if section != 'taboos':
            for sentence in _constraint_sentences(content):
                add('taboos', title or 'constraint', sentence, [entry['id']])
    return sections


def card_source_hash(core: dict, lorebook: dict) -> str:
    entries = [
        {
            'id': item.get('id'),
            'title': item.get('title'),
            'content': item.get('content'),
            'entryType': item.get('entryType'),
        }
        for item in _enabled_lorebook_entries(lorebook)
    ]
    core_desc = core.get('coreDescription', {}) if isinstance(core.get('coreDescription'), dict) else {}
    payload = {
        'name': core.get('name'),
        'scenario': core_desc.get('tagline'),
        'summary': core_desc.get('summary'),
        'entries': entries,
    }
    return hashlib.md5(json.dumps(payload, ensure_ascii=False, sort_keys=True).encode('utf-8')).hexdigest()


# ---------------------------------------------------------------------------
# merge: card always wins
# ---------------------------------------------------------------------------

def _negated_terms(card_sections: dict[str, list[dict]]) -> set[str]:
    """Terms the card explicitly denies or forbids (e.g. '不存在魔法' -> '魔法')."""
    terms: set[str] = set()
    # Only strong denial markers feed term extraction; weak ones like '没有'
    # ('没有人知道…') would produce noisy terms and drop good entries.
    zh_markers = '|'.join(re.escape(item) for item in DENIAL_MARKERS_ZH)
    zh_pattern = re.compile(rf'(?:{zh_markers})(?:任何形式的|任何|一切)?([\u4e00-\u9fff、]{{2,16}})')
    en_patterns = (
        re.compile(r"\b(?:no|never any|without|forbids?|prohibits?)\s+([a-z][a-z\-]{2,24}(?:\s[a-z][a-z\-]{2,24})?)"),
        re.compile(r"\b([a-z][a-z\-]{2,24})\s+(?:does not|do not|doesn't|don't|cannot|can't)\s+exist"),
        re.compile(r"\b([a-z][a-z\-]{2,24})\s+(?:is|are)\s+(?:forbidden|prohibited|banned|impossible)"),
    )
    for entries in card_sections.values():
        for entry in entries:
            text = str(entry.get('text', '') or '')
            for match in zh_pattern.finditer(text):
                # '不存在火器与魔法' -> {'火器', '魔法'}
                for part in re.split(r'[、与和及或]', match.group(1)):
                    term = re.sub(r'[的之在了]+$', '', part)[:6]
                    if len(term) >= 2:
                        terms.add(term)
            lower = text.lower()
            for pattern in en_patterns:
                for match in pattern.finditer(lower):
                    term = match.group(1).strip()
                    if term not in {'one', 'the', 'such', 'any', 'more', 'longer', 'other'}:
                        terms.add(term)
    return terms


def _contradicts_card(text: str, negated: set[str]) -> str | None:
    if not negated:
        return None
    lower = str(text or '').lower()
    if _has_negation(lower):
        # The inferred entry itself restates a limit; that is compatible.
        return None
    for term in negated:
        if term and term in lower:
            return term
    return None


def _normalize_inferred_entry(raw: Any) -> dict | None:
    if isinstance(raw, str):
        raw = {'text': raw}
    if not isinstance(raw, dict):
        return None
    text = _compact(raw.get('text', '') or raw.get('summary', ''), INFERRED_ENTRY_TEXT_LIMIT)
    if not text:
        return None
    title = _compact(raw.get('title', '') or '', 60)
    return {'title': title, 'text': text}


def merge_world_bible(
    card_sections: dict[str, list[dict]],
    inferred_sections: dict[str, Any] | None,
) -> tuple[dict[str, list[dict]], list[dict]]:
    """Merge model output under card entries. Card entries are never altered.

    Returns ``(sections, dropped)`` where ``dropped`` lists inferred entries
    rejected because they duplicated a card entry, collided with a card title,
    or contradicted a card prohibition.
    """
    merged = empty_sections()
    dropped: list[dict] = []
    card_titles: dict[str, set[str]] = {}
    all_card_texts: list[str] = []
    for section in SECTIONS:
        entries = card_sections.get(section, []) if isinstance(card_sections.get(section), list) else []
        for entry in entries:
            if not isinstance(entry, dict) or not str(entry.get('text', '') or '').strip():
                continue
            card_entry = dict(entry)
            card_entry['source'] = SOURCE_CARD
            merged[section].append(card_entry)
            all_card_texts.append(str(card_entry['text']))
        card_titles[section] = {str(item.get('title', '') or '').strip().lower() for item in merged[section] if item.get('title')}
    negated = _negated_terms(merged)

    raw_sections = inferred_sections if isinstance(inferred_sections, dict) else {}
    for section in SECTIONS:
        raw_items = raw_sections.get(section, [])
        if not isinstance(raw_items, list):
            continue
        kept = 0
        for raw in raw_items:
            entry = _normalize_inferred_entry(raw)
            if entry is None:
                continue
            reason = ''
            title_key = entry['title'].strip().lower()
            if title_key and title_key in card_titles.get(section, set()):
                reason = 'title_collides_with_card'
            elif any(_similarity(entry['text'], card_text) >= DUPLICATE_SIMILARITY for card_text in all_card_texts):
                reason = 'duplicates_card'
            else:
                term = _contradicts_card(entry['text'], negated)
                if term:
                    reason = f'contradicts_card:{term}'
            if not reason and any(_similarity(entry['text'], item['text']) >= DUPLICATE_SIMILARITY for item in merged[section]):
                reason = 'duplicates_inferred'
            if not reason and kept >= MAX_INFERRED_ENTRIES_PER_SECTION:
                reason = 'section_limit'
            if reason:
                dropped.append({'section': section, 'title': entry['title'], 'text': entry['text'], 'reason': reason})
                continue
            merged[section].append({
                'id': _stable_id('inf', f"{section}:{entry['text']}"),
                'title': entry['title'],
                'text': entry['text'],
                # Provenance is assigned here, never taken from the model.
                'source': SOURCE_INFERRED,
            })
            kept += 1
    return merged, dropped


