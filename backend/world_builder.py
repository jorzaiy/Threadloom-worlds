def _negated_terms(card_sections: dict[str, list[dict]]) -> set[str]:
    """Terms the card explicitly denies or forbids (e.g. '不存在魔法' -> '魔法')."""
    terms: set[str] = set()
    # Only strong denial markers feed term extraction; weak ones like '没有'
    # ('没有人知道…') would produce noisy terms and drop good entries.
    zh_markers = '|'.join(re.escape(item) for item in DENIAL_MARKERS_ZH)
    zh_pattern = re.compile(rf'(?:{zh_markers})(?:任何形式的|任何|一切)?([\u4e00-\u9fff、]{{2,16}})')
    en_patterns = (
        re.compile(r"\b(?:no|never any|without|forbids?|prohibits?)\s+([a-z][a-z\-]{2,24}(?:\s[a-z][a-z\-]{2,24})?)"),
        re.compile(r"\b([a-z][a-z\-]{2,24})\s+(?:does not|do not|doesn't|don't|cannot|can't)\s+exist"),
        re.compile(r"\b([a-z][a-z\-]{2,24})\s+(?:is|are)\s+(?:forbidden|prohibited|banned|impossible)"),
    )
    for entries in card_sections.values():
        for entry in entries:
            text = str(entry.get('text', '') or '')
            for match in zh_pattern.finditer(text):
                # '不存在火器与魔法' -> {'火器', '魔法'}
                for part in re.split(r'[、与和及或]', match.group(1)):
                    term = re.sub(r'[的之在了]+$', '', part)[:6]
                    if len(term) >= 2:
                        terms.add(term)
            lower = text.lower()
            for pattern in en_patterns:
                for match in pattern.finditer(lower):
                    term = match.group(1).strip()
                    if term not in {'one', 'the', 'such', 'any', 'more', 'longer', 'other'}:
                        terms.add(term)
    return terms


def _contradicts_card(text: str, negated: set[str]) -> str | None:
    if not negated:
        return None
    lower = str(text or '').lower()
    if _has_negation(lower):
        # The inferred entry itself restates a limit; that is compatible.
        return None
    for term in negated:
        if term and term in lower:
            return term
    return None


def _normalize_inferred_entry(raw: Any) -> dict | None:
    if isinstance(raw, str):
        raw = {'text': raw}
    if not isinstance(raw, dict):
        return None
    text = _compact(raw.get('text', '') or raw.get('summary', ''), INFERRED_ENTRY_TEXT_LIMIT)
    if not text:
        return None
    title = _compact(raw.get('title', '') or '', 60)
    entry = {'title': title, 'text': text}
    region = _compact(raw.get('region', '') or '', REGION_TEXT_LIMIT)
    if region:
        entry['region'] = region
    refs = raw.get('refs')
    if isinstance(refs, str):
        refs = [refs]
    if isinstance(refs, list):
        clean = []
        for ref in refs:
            ref_id = str(ref or '').strip().strip('[]').upper()
            if re.fullmatch(r'R\d{1,2}', ref_id) and ref_id not in clean:
                clean.append(ref_id)
        if clean:
            entry['refs'] = clean[:4]
    return entry


def inferred_limit(section: str) -> int:
    return MAX_INFERRED_BY_SECTION.get(section, MAX_INFERRED_ENTRIES_PER_SECTION)


def merge_world_bible(
    card_sections: dict[str, list[dict]],
    inferred_sections: dict[str, Any] | None,
    valid_refs: set[str] | None = None,
) -> tuple[dict[str, list[dict]], list[dict]]:
    """Merge model output under card entries. Card entries are never altered.

    Returns ``(sections, dropped)`` where ``dropped`` lists inferred entries
    rejected because they duplicated a card entry, collided with a card title,
    or contradicted a card prohibition.
    """
    merged = empty_sections()
    dropped: list[dict] = []
    card_titles: dict[str, set[str]] = {}
    all_card_texts: list[str] = []
    for section in SECTIONS:
        entries = card_sections.get(section, []) if isinstance(card_sections.get(section), list) else []
        for entry in entries:
            if not isinstance(entry, dict) or not str(entry.get('text', '') or '').strip():
                continue
            card_entry = dict(entry)
            card_entry['source'] = SOURCE_CARD
            merged[section].append(card_entry)
            all_card_texts.append(str(card_entry['text']))
        card_titles[section] = {str(item.get('title', '') or '').strip().lower() for item in merged[section] if item.get('title')}
    negated = _negated_terms(merged)

    raw_sections = inferred_sections if isinstance(inferred_sections, dict) else {}
    for section in SECTIONS:
        raw_items = raw_sections.get(section, [])
        if not isinstance(raw_items, list):
            continue
        kept = 0
        for raw in raw_items:
            entry = _normalize_inferred_entry(raw)
            if entry is None:
                continue
            reason = ''
            title_key = entry['title'].strip().lower()
            if title_key and title_key in card_titles.get(section, set()):
                reason = 'title_collides_with_card'
            elif any(_similarity(entry['text'], card_text) >= DUPLICATE_SIMILARITY for card_text in all_card_texts):
                reason = 'duplicates_card'
            else:
                term = _contradicts_card(entry['text'], negated)
                if term:
                    reason = f'contradicts_card:{term}'
            if not reason and any(_similarity(entry['text'], item['text']) >= DUPLICATE_SIMILARITY for item in merged[section]):
                reason = 'duplicates_inferred'
            if not reason and kept >= inferred_limit(section):
                reason = 'section_limit'
            if reason:
                dropped.append({'section': section, 'title': entry['title'], 'text': entry['text'], 'reason': reason})
                continue
            item = {
                'id': _stable_id('inf', f"{section}:{entry['text']}"),
                'title': entry['title'],
                'text': entry['text'],
                # Provenance is assigned here, never taken from the model.
                'source': SOURCE_INFERRED,
            }
            if entry.get('region'):
                item['region'] = entry['region']
            refs = [ref for ref in entry.get('refs', []) if valid_refs and ref in valid_refs]
            if refs:
                item['refs'] = refs
            merged[section].append(item)
            kept += 1
    return merged, dropped


