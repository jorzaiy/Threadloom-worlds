def build_world_bible(core: dict, lorebook: dict, *, use_llm: bool = True, use_tavily: bool = True) -> dict:
    card_sections = extract_card_sections(core, lorebook)
    status: dict[str, str] = {}
    research: list[dict] = []
    research_plan: dict[str, Any] = {}
    queries: list[dict] = []
    if use_tavily:
        if str(os.environ.get(TAVILY_API_KEY_ENV, '') or '').strip():
            queries, research_plan = plan_research_queries(core, card_sections)
            status['research_plan'] = research_plan.get('status', '')
            if research_plan.get('mode') == 'none' and research_plan.get('status', '').startswith('ok'):
                status['tavily'] = 'skipped:planner_none'
        if 'tavily' not in status:
            research, status['tavily'] = fetch_tavily_research(core, card_sections, queries, research_plan.get('era_terms') or [])
    else:
        status['tavily'] = 'skipped:disabled'

    inferred: dict = {}
    setting_type = ''
    model_id = ''
    llm_usage: dict[str, Any] = {}
    if not use_llm:
        status['llm'] = 'skipped:disabled'
    elif not nebius_api_key_configured():
        status['llm'] = 'skipped:no_nebius_api_key'
        logger.info('world_builder: NEBIUS_API_KEY not set; writing card-only world bible')
    else:
        try:
            inferred, setting_type, usage = _infer_with_llm(core, card_sections, research, research_plan)
            model_id = str(usage.get('model', '') or '')
            llm_usage = {
                key: usage[key]
                for key in ('input_tokens', 'output_tokens', 'reasoning_tokens', 'duration_ms', 'response_format_fallback')
                if key in usage
            }
            status['llm'] = 'ok'
        except Exception as err:
            logger.warning('world_builder: inference failed, keeping card-only world bible: %s', err)
            status['llm'] = f'error:{_compact(f"{type(err).__name__}: {err}", 200)}'
            inferred = {}

    sections, dropped = merge_world_bible(card_sections, inferred, {note['id'] for note in research if note.get('id')})
    cited = {ref for items in sections.values() for item in items for ref in item.get('refs', [])}
    return {
        'version': WORLD_BIBLE_VERSION,
        'generated_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'character_name': str(core.get('name', '') or ''),
        'source_hash': card_source_hash(core, lorebook),
        'locked': False,
        'setting_type': setting_type,
        'models': {'inferred': model_id},
        'llm_usage': llm_usage,
        'status': status,
        'sections': sections,
        'research': [
            {
                'id': note.get('id', ''),
                'title': note.get('title', ''),
                'url': note.get('url', ''),
                'query': note.get('query', ''),
                'cited': note.get('id', '') in cited,
            }
            for note in research
        ],
        'research_plan': {
            key: research_plan[key]
            for key in ('mode', 'analog', 'era_terms', 'model', 'duration_ms')
            if research_plan.get(key)
        } | ({'queries': [q['query'] for q in queries]} if queries else {}),
        'dropped_inferred': dropped,
        'counts': {
            SOURCE_CARD: sum(1 for items in sections.values() for item in items if item.get('source') == SOURCE_CARD),
            SOURCE_INFERRED: sum(1 for items in sections.values() for item in items if item.get('source') == SOURCE_INFERRED),
        },
    }


def _report(path: Path, bible: dict, *, action: str) -> dict:
    counts = bible.get('counts', {}) if isinstance(bible.get('counts'), dict) else {}
    return {
        'success': True,
        'action': action,
        'world_bible': str(path),
        'status': bible.get('status', {}),
        'card_entries': counts.get(SOURCE_CARD, 0),
        'inferred_entries': counts.get(SOURCE_INFERRED, 0),
        'dropped_inferred': len(bible.get('dropped_inferred', []) or []),
    }


def rebuild_world_bible(
    source_root: Path | None = None,
    *,
    force: bool = False,
    use_llm: bool = True,
    use_tavily: bool = True,
) -> dict:
    """Build ``world-bible.json`` in ``source_root``. Never raises on LLM errors.

    When the existing bible was built from the same card (``source_hash``
    matches) it is reused if it is ``locked`` (user-curated) or inference
    already succeeded, unless ``force`` is set. A bible from a different card
    is always rebuilt, lock or not.
    """
    root = source_root or character_source_base()
    path = root / WORLD_BIBLE_FILE
    core = _read_json(root / 'character-data.json')
    lorebook = _read_json(root / 'lorebook.json')
    existing = _read_json(path)
    if existing and not force and existing.get('source_hash') == card_source_hash(core, lorebook):
        if existing.get('locked') is True:
            return _report(path, existing, action='kept_locked')
        existing_status = existing.get('status', {}) if isinstance(existing.get('status'), dict) else {}
        if existing_status.get('llm') == 'ok':
            return _report(path, existing, action='kept_cached')
    bible = build_world_bible(core, lorebook, use_llm=use_llm, use_tavily=use_tavily)
    atomic_write_json(path, bible)
    return _report(path, bible, action='rebuilt')


def load_world_bible(source_root: Path | None = None) -> dict:
    root = source_root or character_source_base()
    return _read_json(root / WORLD_BIBLE_FILE)


def _count_sources(sections: dict[str, list[dict]]) -> dict[str, int]:
    return {
        source: sum(1 for items in sections.values() for item in items if item.get('source') == source)
        for source in SOURCES
    }


def save_world_bible_edits(
    sections: Any = None,
    *,
    locked: Any = None,
    source_root: Path | None = None,
) -> dict:
    """Apply user edits from the UI. Raises ``ValueError`` on bad input.

    * Entries keep their ``source``; an edited text marks ``edited: true``.
      Edits to a ``card`` entry are allowed (the user owns the card) and the
      entry stays canon. New entries get ``source: "user"`` (also canon).
    * Saving sections locks the bible unless ``locked`` is given explicitly,
      so a later import/rebuild cannot silently overwrite curated edits.
    """
    root = source_root or character_source_base()
    path = root / WORLD_BIBLE_FILE
    bible = _read_json(path)
    if not bible:
        raise ValueError('no world bible for the active character; import a card first')
    if sections is not None:
        if not isinstance(sections, dict):
            raise ValueError('sections must be an object')
        unknown = [name for name in sections if name not in SECTIONS]
        if unknown:
            raise ValueError(f'unknown sections: {", ".join(sorted(unknown))}')
        previous = bible.get('sections') if isinstance(bible.get('sections'), dict) else {}
        prev_by_id = {
            str(item.get('id')): item
            for items in previous.values() if isinstance(items, list)
            for item in items if isinstance(item, dict) and item.get('id')
        }
        cleaned = empty_sections()
        for name in SECTIONS:
            raw_entries = sections.get(name, previous.get(name, []))
            if not isinstance(raw_entries, list):
                raise ValueError(f'section {name} must be a list')
            if len(raw_entries) > EDIT_MAX_ENTRIES_PER_SECTION:
                raise ValueError(f'section {name} has more than {EDIT_MAX_ENTRIES_PER_SECTION} entries')
            for raw in raw_entries:
                if isinstance(raw, str):
                    raw = {'text': raw}
                if not isinstance(raw, dict):
                    raise ValueError(f'section {name} entries must be objects')
                text = ' '.join(str(raw.get('text', '') or '').split())
                if not text:
                    continue
                if len(text) > EDIT_ENTRY_TEXT_LIMIT:
                    raise ValueError(f'entry text longer than {EDIT_ENTRY_TEXT_LIMIT} characters')
                prev = prev_by_id.get(str(raw.get('id') or ''))
                if prev:
                    entry = dict(prev)
                    if text != prev.get('text'):
                        entry['text'] = text
                        entry['edited'] = True
                else:
                    entry = {'id': _stable_id('user', f'{name}:{text}'), 'title': '', 'text': text, 'source': SOURCE_USER}
                if 'title' in raw:
                    entry['title'] = _compact(raw.get('title', '') or '', 60)
                if 'region' in raw:
                    region = _compact(raw.get('region', '') or '', REGION_TEXT_LIMIT)
                    if region:
                        entry['region'] = region
                    else:
                        entry.pop('region', None)
                cleaned[name].append(entry)
        bible['sections'] = cleaned
        bible['counts'] = _count_sources(cleaned)
        bible['edited_at'] = datetime.now(timezone.utc).isoformat(timespec='seconds')
        if locked is None:
            locked = True
    if locked is not None:
        bible['locked'] = bool(locked)
    atomic_write_json(path, bible)
    return bible


def safe_rebuild_world_bible(source_root: Path | None = None, **kwargs: Any) -> dict:
    """Import-time wrapper: any failure is logged and reported, never raised."""
    try:
        return rebuild_world_bible(source_root, **kwargs)
    except Exception as err:
        logger.exception('world_builder: world bible build failed; card import continues')
        return {'success': False, 'error': f'{type(err).__name__}: {err}'}


def main() -> int:
    parser = argparse.ArgumentParser(description='Build the Threadloom world bible (world-bible.json) for a character source.')
    parser.add_argument('--source-root', help='Character source directory containing lorebook.json. Defaults to active character source.')
    parser.add_argument('--lorebook', help='Explicit lorebook.json path; outputs next to it.')
    parser.add_argument('--force', action='store_true', help='Rebuild even if the bible is locked or cached for the same card.')
    parser.add_argument('--no-llm', action='store_true', help='Card-derived entries only; skip Nemotron inference.')
    parser.add_argument('--no-tavily', action='store_true', help='Skip the optional Tavily research lookup.')
    args = parser.parse_args()
    if args.lorebook:
        root = Path(args.lorebook).expanduser().resolve().parent
    elif args.source_root:
        root = Path(args.source_root).expanduser().resolve()
    else:
        root = lorebook_path().parent
    report = rebuild_world_bible(root, force=args.force, use_llm=not args.no_llm, use_tavily=not args.no_tavily)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


