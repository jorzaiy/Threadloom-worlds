def _enabled_lorebook_entries(lorebook: dict) -> list[dict]:
    entries = lorebook.get('entries', []) if isinstance(lorebook.get('entries'), list) else []
    out = []
    for index, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            continue
        if entry.get('disable') is True or entry.get('enabled') is False:
            continue
        content = str(entry.get('content', '') or '').strip()
        if not content:
            continue
        item = dict(entry)
        item['id'] = str(entry.get('id', '') or '').strip() or f'entry-{index}'
        out.append(item)
    return out


def _is_meta_entry(entry: dict) -> bool:
    haystack = f" {entry.get('title', '')} {str(entry.get('content', ''))[:300]} ".lower()
    return any(marker in haystack for marker in META_MARKERS)


def _keyword_hits(word: str, text: str) -> bool:
    if word.isascii():
        # Whole-word match for English ('caste' must not match 'caster'),
        # tolerating a plural suffix ('faction' -> 'factions').
        return re.search(rf'\b{re.escape(word)}(?:s|es)?\b', text) is not None
    return word in text


def classify_section(title: str, content: str, entry_type: str = '') -> str | None:
    """Pick the best world-bible section for a lorebook entry, or ``None``."""
    title_l = str(title or '').lower()
    head_l = str(content or '')[:400].lower()
    scores: dict[str, int] = {name: 0 for name in SECTIONS}
    for section, words in SECTION_KEYWORDS.items():
        for word in words:
            if _keyword_hits(word, title_l):
                scores[section] += 3
            if _keyword_hits(word, head_l):
                scores[section] += 1
    mapped = ENTRY_TYPE_SECTION.get(str(entry_type or '').strip())
    if mapped:
        scores[mapped] += 2
    best = max(SECTIONS, key=lambda name: (scores[name], -SECTIONS.index(name)))
    return best if scores[best] > 0 else None


def _constraint_sentences(text: str, limit: int = 3) -> list[str]:
    parts = re.split(r'(?<=[。！？!?；;\n])|(?<=\.)\s+', str(text or ''))
    out = []
    for part in parts:
        sentence = part.strip()
        if 4 <= len(sentence) <= 200 and _has_negation(sentence):
            out.append(sentence)
        if len(out) >= limit:
            break
    return out


def extract_card_sections(core: dict, lorebook: dict) -> dict[str, list[dict]]:
    """Build card-sourced entries from character core + normalized lorebook."""
    sections = empty_sections()

    def add(section: str, title: str, text: str, entry_ids: list[str]) -> None:
        bucket = sections[section]
        if len(bucket) >= MAX_CARD_ENTRIES_PER_SECTION:
            return
        clean = _compact(text, CARD_ENTRY_TEXT_LIMIT)
        if not clean or any(_similarity(clean, item['text']) >= 0.9 for item in bucket):
            return
        bucket.append({
            'id': _stable_id('card', f'{section}:{clean}'),
            'title': _compact(title, 60),
            'text': clean,
            'source': SOURCE_CARD,
            'source_entry_ids': entry_ids,
        })

    core_desc = core.get('coreDescription', {}) if isinstance(core.get('coreDescription'), dict) else {}
    scenario = str(core_desc.get('tagline', '') or '').strip()
    if scenario:
        add('era_feel', 'Scenario', scenario, ['card:scenario'])

    for entry in _enabled_lorebook_entries(lorebook):
        entry_type = str(entry.get('entryType', '') or '').strip()
        if entry_type == 'npc' or _is_meta_entry(entry):
            continue
        title = str(entry.get('title', '') or entry.get('name', '') or '').strip()
        content = str(entry.get('content', '') or '')
        section = classify_section(title, content, entry_type)
        if section is None:
            continue
        add(section, title or section, content, [entry['id']])
        if section != 'taboos':
            for sentence in _constraint_sentences(content):
                add('taboos', title or 'constraint', sentence, [entry['id']])
    return sections


def card_source_hash(core: dict, lorebook: dict) -> str:
    entries = [
        {
            'id': item.get('id'),
            'title': item.get('title'),
            'content': item.get('content'),
            'entryType': item.get('entryType'),
        }
        for item in _enabled_lorebook_entries(lorebook)
    ]
    core_desc = core.get('coreDescription', {}) if isinstance(core.get('coreDescription'), dict) else {}
    payload = {
        'name': core.get('name'),
        'scenario': core_desc.get('tagline'),
        'summary': core_desc.get('summary'),
        'entries': entries,
    }
    return hashlib.md5(json.dumps(payload, ensure_ascii=False, sort_keys=True).encode('utf-8')).hexdigest()


