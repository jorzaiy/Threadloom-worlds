#!/usr/bin/env python3
"""World Builder: turn an imported character card into a ``world-bible.json``.

The world bible sits next to the distilled lorebook output of the active
character source (``lorebook-foundation.json`` / ``lorebook-index.json``) and
holds seven sections:

- geography
- factions
- social_system
- tech_supernatural_limits
- economy_resources
- taboos
- era_feel

Every entry is ``{"text": ..., "source": "card" | "inferred", ...}``.

* ``card`` entries are extracted deterministically from the card itself
  (scenario + lorebook entries). No model touches them, so their provenance
  is exact and they carry ``source_entry_ids`` back to the lorebook.
* ``inferred`` entries are generated by NVIDIA Nemotron Ultra on Nebius Token
  Factory to fill gaps the card leaves open. They are advisory: the merge step
  (:func:`merge_world_bible`) guarantees card entries win — inferred entries
  that duplicate, claim card provenance, or contradict a card prohibition are
  dropped and recorded in ``dropped_inferred``.

An optional Tavily lookup (``TAVILY_API_KEY``) adds real-world reference notes
for realistic / historical settings. It is skipped silently when the key is
absent or the setting looks fictional.

Failures in the LLM or Tavily steps never raise out of
:func:`rebuild_world_bible`; the bible is still written with card entries only
and the error is recorded in ``status``.
"""

