def build_world_bible(core: dict, lorebook: dict, *, use_llm: bool = True, use_tavily: bool = True) -> dict:
    card_sections = extract_card_sections(core, lorebook)
    status: dict[str, str] = {}
    research: list[dict] = []
    if use_tavily:
        research, status['tavily'] = fetch_tavily_research(core, card_sections)
    else:
        status['tavily'] = 'skipped:disabled'

    inferred: dict = {}
    setting_type = ''
    model_id = ''
    if not use_llm:
        status['llm'] = 'skipped:disabled'
    elif not nebius_api_key_configured():
        status['llm'] = 'skipped:no_nebius_api_key'
        logger.info('world_builder: NEBIUS_API_KEY not set; writing card-only world bible')
    else:
        try:
            inferred, setting_type, usage = _infer_with_llm(core, card_sections, research)
            model_id = str(usage.get('model', '') or '')
            status['llm'] = 'ok'
        except Exception as err:
            logger.warning('world_builder: inference failed, keeping card-only world bible: %s', err)
            status['llm'] = f'error:{_compact(f"{type(err).__name__}: {err}", 200)}'
            inferred = {}

    sections, dropped = merge_world_bible(card_sections, inferred)
    return {
        'version': WORLD_BIBLE_VERSION,
        'generated_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'character_name': str(core.get('name', '') or ''),
        'source_hash': card_source_hash(core, lorebook),
        'locked': False,
        'setting_type': setting_type,
        'models': {'inferred': model_id},
        'status': status,
        'sections': sections,
        'research': [{'title': note.get('title', ''), 'url': note.get('url', '')} for note in research],
        'dropped_inferred': dropped,
        'counts': {
            SOURCE_CARD: sum(1 for items in sections.values() for item in items if item.get('source') == SOURCE_CARD),
            SOURCE_INFERRED: sum(1 for items in sections.values() for item in items if item.get('source') == SOURCE_INFERRED),
        },
    }


def _report(path: Path, bible: dict, *, action: str) -> dict:
    counts = bible.get('counts', {}) if isinstance(bible.get('counts'), dict) else {}
    return {
        'success': True,
        'action': action,
        'world_bible': str(path),
        'status': bible.get('status', {}),
        'card_entries': counts.get(SOURCE_CARD, 0),
        'inferred_entries': counts.get(SOURCE_INFERRED, 0),
        'dropped_inferred': len(bible.get('dropped_inferred', []) or []),
    }


def rebuild_world_bible(
    source_root: Path | None = None,
    *,
    force: bool = False,
    use_llm: bool = True,
    use_tavily: bool = True,
) -> dict:
    """Build ``world-bible.json`` in ``source_root``. Never raises on LLM errors.

    When the existing bible was built from the same card (``source_hash``
    matches) it is reused if it is ``locked`` (user-curated) or inference
    already succeeded, unless ``force`` is set. A bible from a different card
    is always rebuilt, lock or not.
    """
    root = source_root or character_source_base()
    path = root / WORLD_BIBLE_FILE
    core = _read_json(root / 'character-data.json')
    lorebook = _read_json(root / 'lorebook.json')
    existing = _read_json(path)
    if existing and not force and existing.get('source_hash') == card_source_hash(core, lorebook):
        if existing.get('locked') is True:
            return _report(path, existing, action='kept_locked')
        existing_status = existing.get('status', {}) if isinstance(existing.get('status'), dict) else {}
        if existing_status.get('llm') == 'ok':
            return _report(path, existing, action='kept_cached')
    bible = build_world_bible(core, lorebook, use_llm=use_llm, use_tavily=use_tavily)
    atomic_write_json(path, bible)
    return _report(path, bible, action='rebuilt')


def safe_rebuild_world_bible(source_root: Path | None = None, **kwargs: Any) -> dict:
    """Import-time wrapper: any failure is logged and reported, never raised."""
    try:
        return rebuild_world_bible(source_root, **kwargs)
    except Exception as err:
        logger.exception('world_builder: world bible build failed; card import continues')
        return {'success': False, 'error': f'{type(err).__name__}: {err}'}


def main() -> int:
    parser = argparse.ArgumentParser(description='Build the Threadloom world bible (world-bible.json) for a character source.')
    parser.add_argument('--source-root', help='Character source directory containing lorebook.json. Defaults to active character source.')
    parser.add_argument('--lorebook', help='Explicit lorebook.json path; outputs next to it.')
    parser.add_argument('--force', action='store_true', help='Rebuild even if the bible is locked or cached for the same card.')
    parser.add_argument('--no-llm', action='store_true', help='Card-derived entries only; skip Nemotron inference.')
    parser.add_argument('--no-tavily', action='store_true', help='Skip the optional Tavily research lookup.')
    args = parser.parse_args()
    if args.lorebook:
        root = Path(args.lorebook).expanduser().resolve().parent
    elif args.source_root:
        root = Path(args.source_root).expanduser().resolve()
    else:
        root = lorebook_path().parent
    report = rebuild_world_bible(root, force=args.force, use_llm=not args.no_llm, use_tavily=not args.no_tavily)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


